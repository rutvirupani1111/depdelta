const BY_KEY = new Map<string, RuleDef>();
for (const r of RULES) {
  BY_KEY.set(r.id.toLowerCase(), r);
  BY_KEY.set(r.slug.toLowerCase(), r);
}

/** Looks a rule up by id (`DD007`), slug (`exfiltration`) or finding id (`DD007-8c1e2a`). */
export function getRule(idOrSlug: string): RuleDef | undefined {
  const k = idOrSlug.trim().toLowerCase();
  return BY_KEY.get(k) ?? BY_KEY.get(k.replace(/-[0-9a-f]{6}$/, ''));
}

export function ruleById(id: string): RuleDef {
  const r = getRule(id);
  if (!r) throw new Error(`unknown rule ${id}`);
  return r;
}
